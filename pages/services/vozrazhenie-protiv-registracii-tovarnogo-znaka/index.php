<section class="lx-section lx-reveal" id="after">
  <span class="lx-section-label">После регистрации</span>
  <h2>После регистрации: возражение против предоставления правовой охраны</h2>
  <p>Если знак уже зарегистрирован, процедура меняется. Теперь это возражение по <a href="https://www.consultant.ru/document/cons_doc_LAW_64629/fab3ae79219dd5f5d60cb4ff67c6d9832f67bedf/" target="_blank" rel="noopener noreferrer">ст. 1512</a>–<a href="https://www.consultant.ru/document/cons_doc_LAW_64629/65a4af0cccfa200fb361da6e731356a369a0ed8e/" target="_blank" rel="noopener noreferrer">1513</a> ГК РФ, которое подаётся в Роспатент и рассматривается коллегией. Правила — приказ № 644/261.</p>

  <h3>Основания и сроки по ст. 1512 ГК РФ</h3>
  <ul class="lx-checklist">
    <li><strong>Абсолютные основания</strong> (пп. 1–5, 8, 9 ст. 1483) — в течение всего срока действия исключительного права.</li>
    <li><strong>Относительные основания</strong> (пп. 6, 7, 10 ст. 1483) — в течение пяти лет со дня публикации сведений о регистрации в официальном бюллетене.</li>
    <li>Для ряда особых оснований — общеизвестный знак с более поздним приоритетом, регистрация на агента, злоупотребление правом — действуют собственные условия, прописанные в ст. 1512.</li>
  </ul>

  <h3>Кто подаёт и как рассматривается</h3>
  <p>По ст. 1513 ГК РФ возражение подаётся в Роспатент. По большинству оснований его вправе подать заинтересованное лицо. По регистрации на агента — заинтересованный обладатель права в стране — участнице Парижской конвенции. Решение коллегии можно оспорить в суде; порядок вступления решения в силу определяется ст. 1248 ГК РФ.</p>
  <p>По правилам приказа № 644/261 возражение можно подать на бумаге (почтой или через окно приёма) либо в электронной форме через официальный сайт Роспатента. Для электронной подачи возражения, отзыва и пояснений используется простая электронная подпись. Первое заседание по возражениям против предоставления охраны знаку назначается не позднее двух месяцев с момента принятия возражения к рассмотрению.</p>
</section>

