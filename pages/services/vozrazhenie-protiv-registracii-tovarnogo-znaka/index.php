  <h2>Документы и доказательственная база</h2>

  <h3>Что составляет доказательную основу</h3>
  <p>Сильный документ строится не на эмоциях, а на сопоставлении фактов. В общем случае в пакет входят:</p>
  <ul class="lx-checklist">
    <li>само обращение или возражение с правовой позицией и ссылками на статьи ГК РФ;</li>
    <li>сравнительная таблица обозначений: графические, фонетические и смысловые признаки, а также однородность товаров и услуг по классам МКТУ;</li>
    <li>подтверждение ваших прав: свидетельства на товарные знаки, выписки из реестров, документы о приоритете;</li>
    <li>для довода по фирменному наименованию — учредительные документы и сведения из ЕГРЮЛ, а главное — документы, подтверждающие реальную деятельность: договоры, накладные, акты, счета, рекламные материалы с датами;</li>
    <li>при необходимости — доказательства известности обозначения и узнаваемости у потребителей.</li>
