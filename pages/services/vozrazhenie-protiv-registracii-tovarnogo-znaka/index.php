<section class="lx-section lx-reveal" id="when">
  <span class="lx-section-label">Выбор процедуры</span>
  <h2>Какую процедуру выбрать: три сценария вместо одного «возражения»</h2>
  <p>Жизнь чужой заявки на товарный знак проходит несколько стадий. От стадии зависит, что именно вы подаёте и кто вправе это делать.</p>

  <div class="lx-card-grid">
    <article class="lx-card lx-reveal">
      <span class="lx-card-num">ст. 1493</span>
      <h3>Обращение против заявки</h3>
      <p><strong>Стадия:</strong> заявка опубликована, решения о регистрации ещё нет.</p>
      <p><strong>Кто подаёт:</strong> любое лицо.</p>
      <p><strong>Пошлина:</strong> отдельной за подачу нет.</p>
    </article>
    <article class="lx-card lx-reveal">
      <span class="lx-card-num">ст. 1500</span>
      <h3>Возражение на решение Роспатента</h3>
      <p><strong>Стадия:</strong> по заявке вынесено решение (отказ, регистрация и т. д.).</p>
      <p><strong>Кто подаёт:</strong> заявитель по своей заявке.</p>
      <p><strong>Пошлина:</strong> есть, зависит от вида решения (см. <a href="#cost">раздел о пошлинах</a>).</p>
    </article>
    <article class="lx-card lx-reveal">
      <span class="lx-card-num">ст. 1512–1513</span>
      <h3>Оспаривание зарегистрированного знака</h3>
      <p><strong>Стадия:</strong> знак уже внесён в реестр.</p>
      <p><strong>Кто подаёт:</strong> заинтересованное лицо (по большинству оснований).</p>
      <p><strong>Пошлина:</strong> 14&nbsp;000&nbsp;₽ по п. 2.28.4 таблицы Роспатента (актуальная редакция — на <a href="https://rospatent.gov.ru/ru/activities/dues/table" target="_blank" rel="noopener noreferrer">rospatent.gov.ru</a>).</p>
    </article>
