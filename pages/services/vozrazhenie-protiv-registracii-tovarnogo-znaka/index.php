<section class="lx-section lx-reveal" id="grounds">
  <span class="lx-section-label">Основания</span>
  <h2>Основания по ГК РФ: когда правовая охрана не может быть предоставлена</h2>
  <p>Основания, по которым можно возражать против заявки или регистрации, перечислены в <a href="https://www.consultant.ru/document/cons_doc_LAW_64629/2e83c7a3d54808ca80d8f0b2a034caa0f7122b57/" target="_blank" rel="noopener noreferrer">ст. 1483 ГК РФ</a>. Не все они одинаково часто встречаются в споре между конкурентами, но вот те, на которых обычно строят позицию.</p>

  <h3>Сходство до степени смешения с вашим знаком</h3>
  <p>Пункт 6 ст. 1483 ГК РФ: нельзя регистрировать обозначение, сходное до степени смешения с чужим товарным знаком, у которого более ранний приоритет, — в отношении однородных товаров и услуг. Под защиту подпадают как зарегистрированные знаки, так и ранее поданные заявки, а также общеизвестные знаки.</p>
  <p>Сходство оценивается по звуковым, графическим и смысловым признакам; однородность — по назначению, составу, условиям реализации, кругу потребителей. Методика экспертизы закреплена в документах Роспатента, например в приказе от 31.12.2009 № 197 (текст опубликован на <a href="https://pravo.ppt.ru/prikaz/rospatent/n-197-23382" target="_blank" rel="noopener noreferrer">портале правовых актов</a>; при цитировании мы сверяем его с официальными источниками). Для вашего случая важно показать эксперту, как именно воспримет обозначения потребитель.</p>

  <h3>Фирменное наименование и коммерческое обозначение</h3>
  <p>Пункт 8 ст. 1483 ГК РФ защищает права на фирменное наименование и коммерческое обозначение, возникшие раньше приоритета спорного знака, если обозначения сходны и деятельность однородна. Экспертиза по собственной инициативе эту норму не проверяет — ей нужны доводы заинтересованного лица. Это один из самых практичных поводов для обращения по ст. 1493: именно вы знаете о своём фирменном наименовании, а эксперт — нет.</p>
  <p>Здесь решает доказательная часть. Нужны документы, показывающие, что вы реально ведёте деятельность, однородную товарам и услугам заявки, и вели её до приоритета заявленного обозначения. Публичные материалы о подходах судов к заинтересованности и фактической деятельности есть, например, в новости <a href="https://pravo.ru/news/244367/" target="_blank" rel="noopener noreferrer">Право.ру о позиции Верховного суда по делу № СИП-360/2021</a> — мы приводим её только как ориентир на тему, без пересказа деталей чужого дела.</p>

