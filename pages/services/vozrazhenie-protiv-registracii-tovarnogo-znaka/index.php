  <h3>Доверенность и представитель</h3>
  <p>Закон не требует, чтобы возражение подавал именно патентный поверенный. Но если вас представляет другое лицо, нужна доверенность. В правилах № 644/261 доверенность названа среди приложений к возражению. Для сложных споров по сходству и однородности обычно привлекают специалиста по товарным знакам: от формулировки довода зависит, как коллегия поймёт спор.</p>

  <h3>Типичные ошибки при самостоятельной подаче</h3>
  <div class="lx-compare-panel">
    <ul class="lx-checklist">
      <li>Смешение процедур: подача «возражения» в коллегию там, где нужно обращение по ст. 1493, или наоборот.</li>
      <li>Ссылка на выдуманный срок. Вместо нормы закона опираются на пересказ из сторонних материалов.</li>
      <li>Довод по фирменному наименованию без доказательств фактической деятельности.</li>
      <li>Сопоставление только по внешнему сходству, без анализа однородности товаров и услуг.</li>
    </ul>
