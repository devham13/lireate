  <p>Практический вывод простой. Если вы увидели чужую заявку в бюллетене и знак ещё не зарегистрирован — это ситуация для обращения по ст. 1493. Если знак уже внесён в реестр — нужно оспаривать предоставление охраны. Если заявка ваша, а Роспатент отказал — это уже возражение заявителя по <a href="https://www.consultant.ru/document/cons_doc_LAW_64629/04d8518205401260b478eea8470dd73a41a97085/" target="_blank" rel="noopener noreferrer">ст. 1500</a>, и к теме «против чужой регистрации» оно не относится.</p>

  <h3>Публикация заявки в бюллетене ФИПС</h3>
  <p>Сведения о поданных заявках публикуются в официальном бюллетене Роспатента. Любое лицо может ознакомиться с документами заявки (ст. 1493 ГК РФ). Именно публикация открывает окно для обращения третьих лиц: оно длится от публикации сведений о заявке до принятия решения о государственной регистрации.</p>

  <h3>Кто вправе обращаться и возражать</h3>
  <p>По ст. 1493 ГК РФ обращение вправе подать любое лицо. Статус «заинтересованного» для самой подачи обращения закон не требует. Но на практике убедительность доводов зависит от того, какие права у вас есть и чем вы их подтверждаете: свидетельство на свой знак, более ранний приоритет, документы о фактической деятельности.</p>
  <p>Для оспаривания уже зарегистрированного знака требования строже. По <a href="https://www.consultant.ru/document/cons_doc_LAW_64629/65a4af0cccfa200fb361da6e731356a369a0ed8e/" target="_blank" rel="noopener noreferrer">ст. 1513 ГК РФ</a> возражение по большинству оснований подаёт заинтересованное лицо. Если спор строится на сходстве с фирменным наименованием или коммерческим обозначением, одной записи в ЕГРЮЛ или кода ОКВЭД обычно недостаточно: нужны доказательства реальной деятельности, однородной товарам и услугам спорного знака. Роспатент в разъяснениях по п. 8 ст. 1483 ГК РФ отдельно указывает на необходимость документальных сведений о такой деятельности. С этим разъяснением можно ознакомиться в <a href="https://pravo.ppt.ru/informatsionnoye-soobshcheniye/234533" target="_blank" rel="noopener noreferrer">публикации на pravo.ppt.ru</a>; это вторичная публикация, поэтому ключевые формулировки мы сверяем с первоисточниками Роспатента.</p>

  <h3>Чем возражение против чужой регистрации не является</h3>
  <p>Чтобы не путаться, зафиксируем два соседних случая.</p>
  <ul class="lx-checklist">
    <li><strong>Возражение на отказ в регистрации вашего знака</strong> — работа с собственной заявкой по ст. 1500 ГК РФ: срок чётко ограничен четырьмя месяцами со дня направления решения (или запрошенных копий противопоставленных материалов, если копии запрошены в течение двух месяцев со дня направления решения). К защите от чужого знака эта процедура отношения не имеет.</li>
    <li><strong>Оспаривание зарегистрированного знака</strong> — ст. 1512 и 1513 ГК РФ, подробнее в <a href="#after">разделе ниже</a>.</li>
