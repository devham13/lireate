<section class="lx-section lx-reveal" id="faq">
  <span class="lx-section-label">FAQ</span>
  <h2>Частые вопросы о возражении против регистрации товарного знака</h2>

  <details class="lx-faq">
    <summary>Куда подать возражение против регистрации товарного знака?</summary>
    <p>Зависит от стадии. Если заявка опубликована, но решения о регистрации нет, подаётся письменное обращение по ст. 1493 ГК РФ в Роспатент (экспертиза заявки в ФИПС). Если знак уже зарегистрирован, подаётся возражение против предоставления правовой охраны в Роспатент по ст. 1512–1513 ГК РФ: на бумаге или в электронной форме через официальный сайт по правилам приказа № 644/261. Актуальные способы подачи сверяйте на сайте ФИПС.</p>
  </details>

  <details class="lx-faq">
    <summary>Какой срок подачи у обращения по ст. 1493 ГК РФ? Правда ли, что это 3 или 5 месяцев с публикации?</summary>
    <p>Нет. В ст. 1493 ГК РФ календарного срока нет. Обращение можно подать после публикации сведений о заявке и до принятия решения о государственной регистрации. Сроки в месяцах относятся к другим процедурам: например, четыре месяца по ст. 1500 — это возражение заявителя на решение по его собственной заявке.</p>
  </details>

  <details class="lx-faq">
    <summary>Сколько стоит возражение в Роспатент?</summary>
    <p>За обращение по ст. 1493 отдельной пошлины нет. За возражение против предоставления охраны товарному знаку по таблице Роспатента (п. 2.28.4) — 14&nbsp;000&nbsp;₽, за возражение заявителя на решение по результатам экспертизы (п. 2.28.2) — 9&nbsp;000&nbsp;₽ независимо от числа классов. Размеры уточняйте в <a href="https://rospatent.gov.ru/ru/activities/dues/table" target="_blank" rel="noopener noreferrer">официальной таблице</a>. Услуги LIREATE оплачиваются отдельно.</p>
  </details>

  <details class="lx-faq">
    <summary>Нужен ли патентный поверенный?</summary>
    <p>ГК РФ не делает его участие обязательным. Но подать документ может представитель по доверенности, и в сложных спорах о сходстве и однородности участие специалиста по товарным знакам помогает правильно выбрать процедуру, основания и доказательства.</p>
  </details>

  <details class="lx-faq">
    <summary>Можно ли возражать против словесного или комбинированного знака?</summary>
    <p>Да. Вид обозначения сам по себе не ограничивает подачу. Значение имеют основания по ст. 1483 ГК РФ: сходство с вашими правами, различительная способность, ввод в заблуждение и другие. Для комбинированных обозначений оценивают совокупное впечатление, а не только словесную часть.</p>
  </details>

  <details class="lx-faq">
    <summary>Чем отличается обращение по ст. 1493 от возражения по ст. 1512–1513?</summary>
    <p>Обращение подаётся против заявки до решения о регистрации, его вправе подать любое лицо, и доводы учитываются при экспертизе (ст. 1499). Возражение по ст. 1512–1513 подаётся против уже зарегистрированного знака, платное, рассматривается коллегией Роспатента, а заинтересованность подавшего оценивается. Сроки тоже разные: по относительным основаниям — пять лет с публикации сведений о регистрации.</p>
  </details>

  <details class="lx-faq">
    <summary>Что делать, если Роспатент отказал в регистрации моего знака из-за чужого?</summary>
    <p>Это возражение заявителя по ст. 1500 ГК РФ с пошлиной по п. 2.28.2 таблицы и сроком четыре месяца (с оговоркой о копиях противопоставленных материалов). К теме страницы это не относится, но мы можем помочь и с этой процедурой.</p>
  </details>

  <details class="lx-faq">
    <summary>Гарантируете ли вы отмену или отказ в регистрации чужого знака?</summary>
    <p>Нет. Решение принимают Роспатент или суд, и закон не позволяет обещать результат. Мы оцениваем основания, готовим документы и подаём в срок, а перспективы озвучиваем честно, до начала работ.</p>
  </details>
</section>

