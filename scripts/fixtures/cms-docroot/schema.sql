DROP TABLE IF EXISTS news;
DROP TABLE IF EXISTS reviews;
DROP TABLE IF EXISTS portfoliocase;

CREATE TABLE IF NOT EXISTS portfoliocase (
  id INT AUTO_INCREMENT PRIMARY KEY,
  region VARCHAR(128) NOT NULL,
  city VARCHAR(128) NOT NULL,
  name VARCHAR(255) NOT NULL,
  time VARCHAR(64) DEFAULT '',
  start_date VARCHAR(32) DEFAULT '',
  finish_date VARCHAR(32) DEFAULT '',
  folder VARCHAR(128) DEFAULT '',
  img_exp VARCHAR(16) DEFAULT 'png',
  kind VARCHAR(128) DEFAULT '',
  fips_link TEXT
) ENGINE=InnoDB DEFAULT CHARSET=utf8;

CREATE TABLE IF NOT EXISTS reviews (
  id INT AUTO_INCREMENT PRIMARY KEY,
  videoUrl VARCHAR(512) DEFAULT '',
  logoUrl VARCHAR(255) DEFAULT '',
  img_link VARCHAR(255) DEFAULT '',
  city VARCHAR(255) DEFAULT '',
  style VARCHAR(255) DEFAULT '',
  site VARCHAR(255) DEFAULT '',
  networkUrl VARCHAR(255) DEFAULT '',
  company VARCHAR(255) DEFAULT ''
) ENGINE=InnoDB DEFAULT CHARSET=utf8;

CREATE TABLE IF NOT EXISTS news (
  id INT AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(512) NOT NULL,
  seo_url VARCHAR(255) NOT NULL,
  alt_name VARCHAR(255) DEFAULT '',
  full_story MEDIUMTEXT,
  date VARCHAR(32) DEFAULT '',
  category INT DEFAULT 0
) ENGINE=InnoDB DEFAULT CHARSET=utf8;